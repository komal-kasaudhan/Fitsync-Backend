const fs = require('fs');
const path = require('path');

const targetDir = path.join(__dirname, '../data/exercises');
if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
}

// Helper to write JSON
function writeGroup(filename, data) {
    fs.writeFileSync(path.join(targetDir, filename), JSON.stringify(data, null, 2), 'utf8');
    console.log(`✅ Saved ${filename} with ${data.length} exercises.`);
}

